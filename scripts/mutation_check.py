# Report
# ---------------------------------------------------------------------------


@dataclasses.dataclass
class MutantResult:
    candidate: MutationCandidate
    killed_targeted: bool
    targeted_note: str
    confirmed_survivor: bool | None = None  # None until/unless it needed full-suite confirmation


def append_jsonl(path: Path, record: dict) -> None:
    """Crash-safety net: a full run takes tens of minutes and a run that gets
    interrupted (killed process, machine sleep, anything short of a clean exit)
    would otherwise lose every result computed so far, because write_report()
    only runs at the very end. Every verdict is appended here as one JSON line,
    opened/written/flushed/closed each time rather than held open, specifically
    so a hard kill loses at most the one in-flight mutant, not the whole run."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(record) + "\n")
        f.flush()


def write_report(
    path: Path,
    args: argparse.Namespace,
    weights: dict[str, int],
    quotas: dict[str, int],
    candidates_by_file: dict[str, list[MutationCandidate]],
    capped_files: list[str],
    results: list[MutantResult],
    runtime_s: float,
    manifest_ok: bool,
    dropped_equivalent_total: int = 0,
) -> None:
    lines: list[str] = []
    lines.append("# Phase 20.3 mutation testing report")
    lines.append("")
    lines.append(
        "Generated by `scripts/mutation_check.py` (committed harness; see that file for the full "
        "design rationale in its module docstring and inline comments). This section is written "
        "by the harness itself and is purely factual: mutant generation, targeted-subset result, "
        "full-suite confirmation. Triage (which class each survivor falls into, and what was done "
        "about it) is a separate, hand-authored section appended below the harness output."
    )
    lines.append("")

    lines.append("## Mutation catalog")
    lines.append("")
    for kind, desc in CATALOG:
        lines.append(f"- `{kind}`: {desc}")
    lines.append("")

    lines.append("## Surface and allocation")
    lines.append("")
    lines.append(f"Budget: {args.budget}. Seed: {args.seed}.")
    lines.append("")
    lines.append("| file | surface line ranges | candidates in surface | quota | capped |")
    lines.append("|---|---|---|---|---|")
    for relpath in weights:
        ranges = TARGETS[relpath]
        range_str = ", ".join(f"{s}-{e}" for s, e in ranges) if ranges != [(1, 10**6)] else "whole file"
        n_candidates = len(candidates_by_file.get(relpath, []))
        lines.append(f"| `{relpath}` | {range_str} | {n_candidates} | {quotas[relpath]} | {'yes' if relpath in capped_files else 'no'} |")
    lines.append("")

    lines.append("## Per-file results")
    lines.append("")
    lines.append("| file | generated | killed (targeted) | survived targeted | confirmed survivors (full suite) |")
    lines.append("|---|---|---|---|---|")
    by_file: dict[str, list[MutantResult]] = {}
    for r in results:
        by_file.setdefault(r.candidate.file, []).append(r)
    total_gen = total_killed = total_survived_targeted = total_confirmed = 0
    for relpath in weights:
        rs = by_file.get(relpath, [])
        gen = len(rs)
        killed = sum(1 for r in rs if r.killed_targeted)
        survived = gen - killed
        confirmed = sum(1 for r in rs if r.confirmed_survivor)
        total_gen += gen
        total_killed += killed
        total_survived_targeted += survived
        total_confirmed += confirmed
        lines.append(f"| `{relpath}` | {gen} | {killed} | {survived} | {confirmed} |")
    lines.append(f"| **total** | **{total_gen}** | **{total_killed}** | **{total_survived_targeted}** | **{total_confirmed}** |")
    lines.append("")

    lines.append("## Confirmed survivors (harness output; triage appended below)")
    lines.append("")
    confirmed = [r for r in results if r.confirmed_survivor]
    if not confirmed:
        lines.append("None.")
    else:
        lines.append("| file:line | kind | mutation (original -> replacement) | note |")
        lines.append("|---|---|---|---|")
        for r in sorted(confirmed, key=lambda r: r.candidate.sort_key()):
            c = r.candidate
            orig = c.original.replace("|", "\\|").replace("\n", " ")
            repl = c.replacement.replace("|", "\\|").replace("\n", " ")
            lines.append(f"| `{c.file}:{c.line}` | {c.kind} | `{orig}` -> `{repl}` | {c.detail} |")
    lines.append("")

    lines.append("## Run metadata")
    lines.append("")
    lines.append(f"- Harness runtime: {runtime_s:.1f}s")
    lines.append(f"- Real src/ and scripts/ sha256 manifest unchanged start-to-end: {'yes' if manifest_ok else 'NO -- SEE ABORT'}")
    lines.append(
        f"- Mechanically-equivalent mutants dropped before selection: {dropped_equivalent_total}. Rule: (1) a "
        "commutative BinOp (ast.Add or ast.Mult) is never offered to identifier_swap, since swapping its two "
        "operands changes nothing in IEEE 754, for any float operands including nan/inf; (2) after generation, "
        "any candidate whose ast.dump(mutated) equals ast.dump(original) (structural comparison, blind to "
        "line/col) is dropped, for any reason, not just rule (1)'s. Mutations that are equivalent for a reason "
        "that requires reasoning about reachable program state rather than pure syntax are NOT dropped here; "
        "they are generated, run, and (if they survive) reported as survivors with the argument stated, in the "
        "triage section, so a reader can disagree with the argument."
    )
    lines.append("")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


