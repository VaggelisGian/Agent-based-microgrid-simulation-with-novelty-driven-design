# ---------------------------------------------------------------------------
# Source-span bookkeeping: exact text splices driven by ast col/lineno offsets.
# ---------------------------------------------------------------------------


class SourceMap:
    """Maps ast (lineno, col_offset) pairs, 1-indexed lines, to absolute character
    offsets into a source string with '\\n' line endings (i.e. the same string that
    was passed to ast.parse), and back. This is what lets a mutation be a splice of
    exact character ranges rather than a whole-file ast.unparse, so everything
    outside the mutated span stays byte-identical to the original."""

    def __init__(self, text: str):
        self.text = text
        self.line_starts = [0]
        for line in text.splitlines(keepends=True):
            self.line_starts.append(self.line_starts[-1] + len(line))

    def offset(self, line: int, col: int) -> int:
        return self.line_starts[line - 1] + col

    def line_col(self, offset: int) -> tuple[int, int]:
        line_idx = bisect.bisect_right(self.line_starts, offset) - 1
        return line_idx + 1, offset - self.line_starts[line_idx]

    def span_text(self, node: ast.AST) -> str:
        return self.text[self.offset(node.lineno, node.col_offset) : self.offset(node.end_lineno, node.end_col_offset)]


def in_range(node: ast.AST, ranges: list[tuple[int, int]]) -> bool:
    lineno = getattr(node, "lineno", None)
    if lineno is None:
        return False
    end_lineno = getattr(node, "end_lineno", lineno)
    return any(start <= lineno and end_lineno <= end for start, end in ranges)


def locate_operator_span(smap: SourceMap, left: ast.AST, right: ast.AST, symbol: str) -> tuple[int, int] | None:
    """ast's operator/cmpop nodes (Add, Lt, ...) carry no position of their own
    (confirmed: ast.parse('a+b').body[0].value.op.lineno is None on this Python).
    The operator token has to live somewhere in the gap between the left operand's
    end and the right operand's start, so find it there instead. Returns None
    (candidate skipped) if the exact symbol cannot be found in that gap, rather
    than guessing a position and risking a corrupt splice."""
    gap_start = smap.offset(left.end_lineno, left.end_col_offset)
    gap_end = smap.offset(right.lineno, right.col_offset)
    gap = smap.text[gap_start:gap_end]
    idx = gap.find(symbol)
    if idx == -1:
        return None
    return gap_start + idx, gap_start + idx + len(symbol)


def read_source(path: Path) -> str:
    """The ONE place source text is decoded, used for both candidate generation
    (offset computation) and mutation application (splicing), so the two can
    never disagree. Path.read_text() would silently do universal-newline
    translation (CRLF -> LF) while Path.read_bytes().decode() would not; this
    codebase's files are CRLF (confirmed: 207 \\r\\n in consumer.py alone), so
    using read_text() for offsets and read_bytes().decode() for splicing (an
    earlier version of this function did exactly that, one call for
    candidate generation, a separate one for the mutation loop) would compute
    every offset against a string 1 character shorter per preceding line than
    the string actually spliced against -- correct on line 1, increasingly
    wrong on every later line. This surfaced as mutations at consumer.py:130
    (deep in a CRLF file) being spliced at the wrong offset and landing on
    inert text, reported as false survivors even after full-suite
    confirmation. Fixed by decoding raw bytes exactly once, one way, reused
    everywhere a given file's text is needed."""
    return path.read_bytes().decode("utf-8")


def build_parents(tree: ast.AST) -> dict[ast.AST, ast.AST]:
    parents: dict[ast.AST, ast.AST] = {}
    for node in ast.walk(tree):
        for child in ast.iter_child_nodes(node):
            parents[child] = node
    return parents


