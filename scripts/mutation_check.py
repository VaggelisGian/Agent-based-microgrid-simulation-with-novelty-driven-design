def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--budget", type=int, default=200, help="total mutants to run (default 200)")
    parser.add_argument("--files", nargs="*", default=None, help="substrings to restrict target files (default: all)")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED, help=f"fixed sampling seed (default {DEFAULT_SEED})")
    parser.add_argument(
        "--report", type=Path, default=REPO_ROOT / "docs" / "verification" / "mutation_report.md", help="output report path"
    )
    parser.add_argument(
        "--augassign-only",
        action="store_true",
        help=(
            "Defect 1 fix's supplement path: generate candidates ONLY from ast.AugAssign nodes "
            "(generate_augassign_candidates), instead of the normal full pool (generate_candidates). "
            "Does not touch or re-select the original 200-mutant campaign's candidate pool; use this "
            "for a separate supplementary run covering the AugAssign gap that pool never saw."
        ),
    )
    parser.add_argument(
        "--offset",
        type=int,
        default=0,
        help=(
            "skip this many entries of the deterministic (budget, seed, files) mutant list before processing "
            "the rest; lets one long run be split into foreground chunks that finish inside a tool timeout. "
            "Chunk N+1's offset is chunk N's offset plus however many mutants chunk N actually processed "
            "(readable from chunk N's .jsonl progress log if it did not finish); the chunks' reports "
            "recombine by hand into one docs/verification/mutation_report.md, since each chunk only ever "
            "sees and reports on its own slice."
        ),
    )
    args = parser.parse_args(argv)

    t0 = time.time()
    progress_path = args.report.with_suffix(".jsonl")
    if progress_path.exists():
        progress_path.unlink()  # each run starts a fresh crash-safety log; stale lines would misreport a new run

    guarded_files = collect_guarded_files(REPO_ROOT)
    manifest_before = compute_manifest(guarded_files)
    print(f"[manifest] hashed {len(guarded_files)} files under src/ and scripts/ (real tree). digest={manifest_digest(manifest_before)[:16]}")

    weights = dict(WEIGHTS)
    if args.files:
        needles = [f.lower() for f in args.files]
        weights = {k: v for k, v in WEIGHTS.items() if any(n in k.lower() for n in needles)}
    if not weights:
        print("no targets matched --files", file=sys.stderr)
        return 1

    # Defect 2 fix (post-hoc adversarial review): everything from here down touches
    # the scratch tree, and the post-run manifest check (below, in `finally`) is
    # the one thing that would catch the real src/scripts/ having been corrupted
    # if any of it crashes. The check used to run only after this whole block
    # returned normally -- the happy path, exactly the path that does NOT need it.
    # Wrapping the block in try/finally means a mid-run crash (an unexpected
    # exception from pytest invocation, candidate generation, anything) still
    # always runs the manifest comparison before that crash is allowed to
    # propagate, instead of skipping straight past it.
    candidates_by_file: dict[str, list[MutationCandidate]] = {}
    quotas: dict[str, int] = {}
    capped_files: list[str] = []
    dropped_equivalent_total = 0
    results: list[MutantResult] = []
    manifest_ok = False
    try:
        scratch_root = prepare_scratch_tree(REPO_ROOT, SCRATCH_ROOT)
        print(f"[scratch] clean copy prepared at {scratch_root}")

        generator = generate_augassign_candidates if args.augassign_only else generate_candidates
        for relpath in weights:
            source_text = read_source(scratch_root / relpath)
            kept, dropped = generator(relpath, source_text, TARGETS[relpath])
            candidates_by_file[relpath] = kept
            dropped_equivalent_total += dropped
            print(f"[generate] {relpath}: {len(kept)} candidate mutations ({dropped} dropped as mechanically equivalent)")

        availability = {relpath: len(candidates_by_file[relpath]) for relpath in weights}
        quotas = allocate_budget(args.budget, weights, availability)
        selected, capped_files = select_mutants(candidates_by_file, quotas, args.seed)
        print(f"[select] {len(selected)} mutants selected for budget {args.budget} (seed {args.seed}); "
              f"{dropped_equivalent_total} dropped as mechanically equivalent before selection")
        if capped_files:
            print(f"[select] quota exceeded available candidates for: {capped_files} (took all available)")
        if args.offset:
            skipped = selected[: args.offset]
            selected = selected[args.offset :]
            print(f"[offset] skipping first {len(skipped)} of the deterministic list; processing {len(selected)} remaining")

        for relpath in weights:
            muts = [c for c in selected if c.file == relpath]
            if not muts:
                continue
            target_path = scratch_root / relpath
            original_bytes = target_path.read_bytes()
            original_text = read_source(target_path)
            pytest_args = targeted_pytest_args(relpath)
            for c in muts:
                mutated_text = c.apply(original_text)
                target_path.write_bytes(mutated_text.encode("utf-8"))
                try:
                    passed, _ = run_pytest(scratch_root, pytest_args, TARGETED_TIMEOUT_S)
                finally:
                    target_path.write_bytes(original_bytes)  # restore inside the SCRATCH tree, always
                killed = not passed
                results.append(MutantResult(c, killed, "targeted subset failed" if killed else "targeted subset passed"))
                print(f"[{'killed' if killed else 'SURVIVED'}] {c.file}:{c.line} {c.kind}: {c.detail}", flush=True)
                append_jsonl(progress_path, {"stage": "targeted", "id": c.mutant_id(), "file": c.file, "line": c.line,
                                              "col": c.col, "kind": c.kind, "detail": c.detail, "killed": killed})

        survivors = [r for r in results if not r.killed_targeted]
        print(f"[confirm] {len(survivors)} targeted-subset survivor(s); re-running each against the full suite")
        for r in survivors:
            c = r.candidate
            target_path = scratch_root / c.file
            original_bytes = target_path.read_bytes()
            original_text = read_source(target_path)
            mutated_text = c.apply(original_text)
            target_path.write_bytes(mutated_text.encode("utf-8"))
            try:
                passed, _ = run_pytest(scratch_root, FULL_SUITE_ARGS, FULL_SUITE_TIMEOUT_S)
            finally:
                target_path.write_bytes(original_bytes)
            r.confirmed_survivor = passed  # still passes the full suite => genuinely survives
            print(
                f"[{'CONFIRMED SURVIVOR' if r.confirmed_survivor else 'killed by full suite'}] {c.file}:{c.line} {c.kind}: {c.detail}",
                flush=True,
            )
            append_jsonl(progress_path, {"stage": "confirm", "id": c.mutant_id(), "file": c.file, "line": c.line,
                                          "col": c.col, "kind": c.kind, "detail": c.detail, "confirmed_survivor": r.confirmed_survivor})
    finally:
        manifest_after = compute_manifest(guarded_files)
        manifest_ok = manifest_before == manifest_after
        print(f"[manifest] real src/scripts unchanged at exit: {manifest_ok}. digest={manifest_digest(manifest_after)[:16]}")
        verify_manifest_or_abort(manifest_before, manifest_after)

    runtime_s = time.time() - t0
    write_report(
        args.report, args, weights, quotas, candidates_by_file, capped_files, results, runtime_s, manifest_ok,
        dropped_equivalent_total,
    )
    print(f"[done] runtime {runtime_s:.1f}s. report written to {args.report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
