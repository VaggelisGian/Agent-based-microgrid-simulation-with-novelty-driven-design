"""Phase 20.3: scoped, deterministic mutation-testing harness.

WHAT THIS DOES. Generates syntactic mutants of the claim-bearing surface defined in
docs/verification/surface.md (hardcoded below rather than parsed from that document,
per the task brief; the line ranges are cited from that document, not guessed), runs
each mutant's targeted test subset, confirms every survivor against the full suite,
and writes docs/verification/mutation_report.md.

SAFETY. This script NEVER writes to the real src/ or scripts/ tree. Every mutation is
applied to a throwaway copy of the repository under a scratch directory outside the
repo (see SCRATCH_ROOT below); the real tree is read from once, to seed that copy, and
otherwise only ever hashed. A sha256 manifest of every file under the real src/ and
scripts/ is taken at startup and again at exit; the two must match exactly or the
script aborts loudly (see verify_manifest_or_abort). This is the reason mutations are
implemented as an in-memory text splice applied to, and then always restored from, a
byte-for-byte copy held in the scratch tree, never as an edit to a path under REPO_ROOT.

DETERMINISM. Mutation candidates are generated by walking each target file's ast once,
producing one MutationCandidate per applicable (node, mutation kind) pair, then sorted
by (file, line, col, kind, detail). If a file's candidate pool exceeds its budget quota,
the quota is drawn with random.Random(seed).sample() (seed fixed by --seed, default
DEFAULT_SEED below) applied to that already-sorted pool, then the sample is re-sorted
into the same fixed order before being run. Two runs at the same --budget and --seed
therefore generate and report on an identical mutant set in an identical order; the
only thing that legitimately differs between two runs is wall-clock runtime, which is
why the report keeps that number on its own line rather than folding it into anything
that is asserted to be reproducible.

USAGE.
    python scripts/mutation_check.py                       # budget 200, default seed
    python scripts/mutation_check.py --budget 12 --report X # small run, custom report path
    python scripts/mutation_check.py --files capacity metrics
"""

