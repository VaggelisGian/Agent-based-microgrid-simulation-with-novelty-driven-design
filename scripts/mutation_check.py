@dataclasses.dataclass(frozen=True)
class MutationCandidate:
    file: str
    line: int
    col: int
    kind: str
    detail: str
    original: str
    replacement: str
    start_offset: int
    end_offset: int

    def sort_key(self):
        return (self.file, self.line, self.col, self.kind, self.detail)

    def mutant_id(self) -> str:
        return f"{self.file}:{self.line}:{self.col}:{self.kind}:{self.detail}"

    def apply(self, source_text: str) -> str:
        return source_text[: self.start_offset] + self.replacement + source_text[self.end_offset :]


_ARITH_SYMBOL = {ast.Add: "+", ast.Sub: "-", ast.Mult: "*", ast.Div: "/", ast.FloorDiv: "//", ast.Mod: "%"}
# One deterministic swap target per operator (not every possible pairing), so the
# catalog stays enumerable: each instance produces exactly one arithmetic mutant.
_ARITH_SWAP = {ast.Add: "-", ast.Sub: "+", ast.Mult: "/", ast.Div: "*", ast.FloorDiv: "%", ast.Mod: "//"}

_CMP_SYMBOL = {ast.Lt: "<", ast.LtE: "<=", ast.Gt: ">", ast.GtE: ">=", ast.Eq: "==", ast.NotEq: "!="}
_CMP_SWAP = {ast.Lt: ">=", ast.LtE: ">", ast.Gt: "<=", ast.GtE: "<", ast.Eq: "!=", ast.NotEq: "=="}

# Defect fix (post-hoc adversarial review of the 200-mutant campaign): the original
# gen_arith_op_swaps only ever walked ast.BinOp, and gen_boundary_shifts' parent
# check only recognized ast.Subscript / ast.Compare / ast.Call / a Div-family
# ast.BinOp as the parent of an int literal. ast.AugAssign (`x += y`) was never
# visited by either, so every augmented assignment in the surface -- every
# accumulator, e.g. capacity.py's total_charge_eur, consumer.py's
# total_deferred_kwh, model.py's broker_contributions_kwh[...] += ... (the exact
# line the Phase 19 surviving mutant A lived on) -- got ZERO candidates, silently,
# in the original 200-mutant campaign. These two symbol maps and the two
# gen_augassign_* generators below give AugAssign the same two mutation kinds
# BinOp/Compare already had; they are deliberately NOT folded into
# gen_arith_op_swaps/gen_boundary_shifts or generate_candidates, so the original
# 200 mutants' identity and selection (already run, already reported) are not
# altered or renumbered by this fix. They are used only by generate_augassign_candidates,
# which only the --augassign-only supplement run below calls.
_AUGASSIGN_SYMBOL = {ast.Add: "+=", ast.Sub: "-=", ast.Mult: "*=", ast.Div: "/=", ast.FloorDiv: "//=", ast.Mod: "%="}
_AUGASSIGN_SWAP = {ast.Add: "-=", ast.Sub: "+=", ast.Mult: "/=", ast.Div: "*=", ast.FloorDiv: "%=", ast.Mod: "//="}


def gen_arith_op_swaps(tree: ast.AST, smap: SourceMap, ranges, relpath: str) -> list[MutationCandidate]:
    out = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.BinOp) and type(node.op) in _ARITH_SWAP and in_range(node, ranges)):
            continue
        symbol = _ARITH_SYMBOL[type(node.op)]
        span = locate_operator_span(smap, node.left, node.right, symbol)
        if span is None:
            continue
        start, end = span
        new_symbol = _ARITH_SWAP[type(node.op)]
        line, col = smap.line_col(start)
        out.append(
            MutationCandidate(
                relpath, line, col, "arith_op_swap", f"{symbol!r} -> {new_symbol!r}", symbol, new_symbol, start, end
            )
        )
    return out


def gen_cmp_op_swaps(tree: ast.AST, smap: SourceMap, ranges, relpath: str) -> list[MutationCandidate]:
    out = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Compare) and len(node.ops) == 1 and in_range(node, ranges)):
            continue
        op_type = type(node.ops[0])
        if op_type not in _CMP_SWAP:
            continue
        symbol = _CMP_SYMBOL[op_type]
        span = locate_operator_span(smap, node.left, node.comparators[0], symbol)
        if span is None:
            continue
        start, end = span
        new_symbol = _CMP_SWAP[op_type]
        line, col = smap.line_col(start)
        out.append(
            MutationCandidate(
                relpath, line, col, "cmp_op_swap", f"{symbol!r} -> {new_symbol!r}", symbol, new_symbol, start, end
            )
        )
    return out


def gen_boundary_shifts(tree: ast.AST, parents, smap: SourceMap, ranges, relpath: str) -> list[MutationCandidate]:
    out = []
    for node in ast.walk(tree):
        # bool is an int subclass; type(...) is int (not isinstance) excludes True/False.
        if not (isinstance(node, ast.Constant) and type(node.value) is int and in_range(node, ranges)):
            continue
        parent = parents.get(node)
        is_index = isinstance(parent, ast.Subscript)
        is_count = isinstance(parent, (ast.Compare, ast.Call))
        is_divisor = isinstance(parent, ast.BinOp) and isinstance(parent.op, (ast.Div, ast.FloorDiv, ast.Mod))
        if not (is_index or is_count or is_divisor):
            continue
        start = smap.offset(node.lineno, node.col_offset)
        end = smap.offset(node.end_lineno, node.end_col_offset)
        orig_text = smap.text[start:end]
        line, col = smap.line_col(start)
        for delta in (-1, 1):
            new_text = str(node.value + delta)
            if new_text == orig_text:
                continue
            out.append(
                MutationCandidate(
                    relpath, line, col, "boundary_shift", f"{orig_text} -> {new_text}", orig_text, new_text, start, end
                )
            )
    return out


def gen_augassign_arith_op_swaps(tree: ast.AST, smap: SourceMap, ranges, relpath: str) -> list[MutationCandidate]:
    """arith_op_swap for ast.AugAssign (`x += y` -> `x -= y`, etc.), the AugAssign
    half of the Defect 1 fix. AugAssign's op, like BinOp's, carries no position of
    its own, so the operator token is located the same way: it lives in the gap
    between the target's end and the value's start."""
    out = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.AugAssign) and type(node.op) in _AUGASSIGN_SWAP and in_range(node, ranges)):
            continue
        symbol = _AUGASSIGN_SYMBOL[type(node.op)]
        span = locate_operator_span(smap, node.target, node.value, symbol)
        if span is None:
            continue
        start, end = span
        new_symbol = _AUGASSIGN_SWAP[type(node.op)]
        line, col = smap.line_col(start)
        out.append(
            MutationCandidate(
                relpath, line, col, "arith_op_swap", f"{symbol!r} -> {new_symbol!r} (augmented assignment)",
                symbol, new_symbol, start, end,
            )
        )
    return out


def gen_augassign_boundary_shifts(tree: ast.AST, parents, smap: SourceMap, ranges, relpath: str) -> list[MutationCandidate]:
    """boundary_shift for an int literal that is directly the right-hand side of an
    ast.AugAssign (e.g. `self.hours_observed += 1`), the other half of the
    Defect 1 fix. Deliberately narrow (the literal must BE parent.value, not
    merely nested somewhere inside it): a literal nested in a larger expression on
    the right-hand side is still reachable through the existing Compare/Call/Div
    parent checks in gen_boundary_shifts wherever those already apply, so this
    only needs to cover the case those checks structurally cannot: the AugAssign
    node itself, which is not a Subscript, Compare, Call, or Div-family BinOp."""
    out = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Constant) and type(node.value) is int and in_range(node, ranges)):
            continue
        parent = parents.get(node)
        if not (isinstance(parent, ast.AugAssign) and parent.value is node):
            continue
        start = smap.offset(node.lineno, node.col_offset)
        end = smap.offset(node.end_lineno, node.end_col_offset)
        orig_text = smap.text[start:end]
        line, col = smap.line_col(start)
        for delta in (-1, 1):
            new_text = str(node.value + delta)
            if new_text == orig_text:
                continue
            out.append(
                MutationCandidate(
                    relpath, line, col, "boundary_shift", f"{orig_text} -> {new_text} (augmented assignment)",
                    orig_text, new_text, start, end,
                )
            )
    return out


def gen_bool_gates(tree: ast.AST, smap: SourceMap, ranges, relpath: str) -> list[MutationCandidate]:
    out = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.If, ast.While)):
            continue
        test = node.test
        if not in_range(test, ranges):
            continue
        start = smap.offset(test.lineno, test.col_offset)
        end = smap.offset(test.end_lineno, test.end_col_offset)
        orig_text = smap.text[start:end]
        line, col = smap.line_col(start)
        for replacement in ("True", "False"):
            if orig_text.strip() == replacement:
                continue
            out.append(
                MutationCandidate(
                    relpath, line, col, "bool_gate", f"condition -> {replacement}", orig_text, replacement, start, end
                )
            )
    return out


def gen_bound_removal_and_sign_flip(tree: ast.AST, smap: SourceMap, ranges, relpath: str) -> list[MutationCandidate]:
    out = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Call) and not node.keywords and in_range(node, ranges)):
            continue
        is_maxmin = isinstance(node.func, ast.Name) and node.func.id in ("max", "min") and len(node.args) == 2
        is_clip = isinstance(node.func, ast.Attribute) and node.func.attr == "clip" and len(node.args) == 3
        if not (is_maxmin or is_clip):
            continue
        start = smap.offset(node.lineno, node.col_offset)
        end = smap.offset(node.end_lineno, node.end_col_offset)
        call_text = smap.text[start:end]
        line, col = smap.line_col(start)

        if is_maxmin:
            func_name = node.func.id
            for i, arg in enumerate(node.args):
                a_start = smap.offset(arg.lineno, arg.col_offset)
                a_end = smap.offset(arg.end_lineno, arg.end_col_offset)
                arg_text = smap.text[a_start:a_end]
                if arg_text == call_text:
                    continue
                out.append(
                    MutationCandidate(
                        relpath,
                        line,
                        col,
                        "bound_removal",
                        f"drop {func_name}(...) wrapper, keep operand {i}",
                        call_text,
                        arg_text,
                        start,
                        end,
                    )
                )
        else:
            arg = node.args[0]
            a_start = smap.offset(arg.lineno, arg.col_offset)
            a_end = smap.offset(arg.end_lineno, arg.end_col_offset)
            arg_text = smap.text[a_start:a_end]
            out.append(
                MutationCandidate(
                    relpath, line, col, "bound_removal", "drop clip(...) wrapper, keep value", call_text, arg_text, start, end
                )
            )

        negated = f"-({call_text})"
        out.append(
            MutationCandidate(
                relpath, line, col, "sign_flip", "negate clipped/bounded quantity", call_text, negated, start, end
            )
        )
    return out


# Swapping the two operands of one of these is a no-op in IEEE 754 (true for +
# and * of any two floats, including nan/inf operands, as far as the returned
# value goes): review finding, not a hypothesis. Swapping operands of a - b,
# a / b, a // b or a % b is NOT a no-op, so those stay eligible.
_COMMUTATIVE_BINOPS = (ast.Add, ast.Mult)


def gen_identifier_swaps(tree: ast.AST, smap: SourceMap, ranges, relpath: str) -> tuple[list[MutationCandidate], int]:
    """'Same-typed' is approximated as 'both operands are bare ast.Name nodes with
    different identifiers': this codebase carries no pervasive static type info to
    check real types against, and a bare-name pair is the case where a swap is both
    syntactically trivial (no wrapping needed) and semantically the classic
    copy-paste-swap bug this catalog item exists to catch.

    Returns (candidates, num_skipped_as_commutative): the second count is only
    incremented for a BinOp that would otherwise have produced a candidate (both
    operands bare, distinct Names) and is a + or a *, so it reflects mutations
    actually prevented, not every commutative BinOp in the file (most have a
    non-Name operand, e.g. a nested sub-expression, and were never candidates)."""
    out = []
    skipped_commutative = 0

    def try_swap(a: ast.AST, b: ast.AST, pos_node: ast.AST, where: str) -> MutationCandidate | None:
        if not (isinstance(a, ast.Name) and isinstance(b, ast.Name)) or a.id == b.id:
            return None
        a_start, a_end = smap.offset(a.lineno, a.col_offset), smap.offset(a.end_lineno, a.end_col_offset)
        b_start, b_end = smap.offset(b.lineno, b.col_offset), smap.offset(b.end_lineno, b.end_col_offset)
        if a_end > b_start:
            return None  # a should lexically precede b; skip anything unexpected rather than risk a bad splice
        pos_start = smap.offset(pos_node.lineno, pos_node.col_offset)
        pos_end = smap.offset(pos_node.end_lineno, pos_node.end_col_offset)
        orig = smap.text[pos_start:pos_end]
        new_text = smap.text[pos_start:a_start] + b.id + smap.text[a_end:b_start] + a.id + smap.text[b_end:pos_end]
        line, col = smap.line_col(pos_start)
        return MutationCandidate(
            relpath, line, col, "identifier_swap", f"swap {a.id!r} <-> {b.id!r} in {where}", orig, new_text, pos_start, pos_end
        )

    for node in ast.walk(tree):
        candidate = None
        if isinstance(node, ast.BinOp) and in_range(node, ranges):
            left, right = node.left, node.right
            would_qualify = isinstance(left, ast.Name) and isinstance(right, ast.Name) and left.id != right.id
            if would_qualify and isinstance(node.op, _COMMUTATIVE_BINOPS):
                skipped_commutative += 1  # a + b -> b + a, or a * b -> b * a: identical value, not a mutation
                continue
            candidate = try_swap(left, right, node, "BinOp")
        elif isinstance(node, ast.Compare) and len(node.ops) == 1 and in_range(node, ranges):
            candidate = try_swap(node.left, node.comparators[0], node, "Compare")
        elif isinstance(node, ast.Call) and len(node.args) >= 2 and in_range(node, ranges):
            candidate = try_swap(node.args[0], node.args[1], node, "Call args")
        if candidate is not None:
            out.append(candidate)
    return out, skipped_commutative


def generate_candidates(relpath: str, source_text: str, ranges: list[tuple[int, int]]) -> tuple[list[MutationCandidate], int]:
    """Returns (candidates, num_dropped_as_mechanically_equivalent).

    The per-kind generators above already refuse a few equivalences they can see
    locally (a commutative BinOp operand swap, a boundary shift that happens to
    reproduce the original text). This is a second, general-purpose net: apply
    EVERY surviving candidate to the source, re-parse the result, and compare
    ast.dump(mutated) to ast.dump(original) (default include_attributes=False,
    so this is a structural comparison, blind to line/col). An identical dump
    means the mutation is a no-op by construction, for any reason, not just the
    ones a specific generator happens to know about -- and it is silently
    dropped, because there is no argument to make about it: two ASTs that dump
    identically denote the identical computation. Anything NOT caught here that
    still turns out to be behaviorally inert is a different kind of claim (it
    requires reasoning about reachable program states, not just syntax), and is
    reported as a survivor with that argument stated, not dropped here."""
    tree = ast.parse(source_text, filename=relpath)
    original_dump = ast.dump(tree)
    smap = SourceMap(source_text)
    parents = build_parents(tree)

    identifier_swap_candidates, skipped_commutative = gen_identifier_swaps(tree, smap, ranges, relpath)

    candidates: list[MutationCandidate] = []
    candidates += gen_arith_op_swaps(tree, smap, ranges, relpath)
    candidates += gen_cmp_op_swaps(tree, smap, ranges, relpath)
    candidates += gen_boundary_shifts(tree, parents, smap, ranges, relpath)
    candidates += gen_bool_gates(tree, smap, ranges, relpath)
    candidates += gen_bound_removal_and_sign_flip(tree, smap, ranges, relpath)
    candidates += identifier_swap_candidates

    seen: set[tuple[int, int, str]] = set()
    unique = []
    for c in candidates:
        key = (c.start_offset, c.end_offset, c.replacement)
        if key in seen:
            continue
        seen.add(key)
        unique.append(c)
    unique.sort(key=lambda c: c.sort_key())

    kept = []
    dropped_equivalent = skipped_commutative
    for c in unique:
        mutated_dump = ast.dump(ast.parse(c.apply(source_text), filename=relpath))
        if mutated_dump == original_dump:
            dropped_equivalent += 1
            continue
        kept.append(c)
    return kept, dropped_equivalent


def generate_augassign_candidates(relpath: str, source_text: str, ranges: list[tuple[int, int]]) -> tuple[list[MutationCandidate], int]:
    """Defect 1 fix: a separate entry point covering ONLY ast.AugAssign, the node
    type generate_candidates never visited (see the _AUGASSIGN_SYMBOL comment
    above). Kept separate from generate_candidates, rather than folded into it, so
    the original 200-mutant campaign's candidate pool -- already generated,
    already selected, already run and reported -- is not changed or renumbered by
    this fix; this function is called only by the --augassign-only supplement.
    Same equivalence guard as generate_candidates (ast.dump comparison, blind to
    line/col), applied to exactly the same source text and ranges."""
    tree = ast.parse(source_text, filename=relpath)
    original_dump = ast.dump(tree)
    smap = SourceMap(source_text)
    parents = build_parents(tree)

    candidates: list[MutationCandidate] = []
    candidates += gen_augassign_arith_op_swaps(tree, smap, ranges, relpath)
    candidates += gen_augassign_boundary_shifts(tree, parents, smap, ranges, relpath)

    seen: set[tuple[int, int, str]] = set()
    unique = []
    for c in candidates:
        key = (c.start_offset, c.end_offset, c.replacement)
        if key in seen:
            continue
        seen.add(key)
        unique.append(c)
    unique.sort(key=lambda c: c.sort_key())

    kept = []
    dropped_equivalent = 0
    for c in unique:
        mutated_dump = ast.dump(ast.parse(c.apply(source_text), filename=relpath))
        if mutated_dump == original_dump:
            dropped_equivalent += 1
            continue
        kept.append(c)
    return kept, dropped_equivalent


# ---------------------------------------------------------------------------
# Budget allocation
# ---------------------------------------------------------------------------


def allocate_budget(budget: int, weights: dict[str, int], availability: dict[str, int]) -> dict[str, int]:
    """Proportional, largest-remainder allocation, water-filled against each file's
    actual candidate count.

    A flat proportional split (e.g. metrics.py gets exactly 60/200 of the budget)
    is not enough on its own: metrics.py's surface only contains 40 candidate
    mutations at all (it is a small, four-branch file), so a flat 60-mutant quota
    would silently under-spend the budget by 20 mutants rather than actually
    running 200. Instead: compute the proportional split among files still under
    their cap, place it, cap any file that overflowed its own availability at
    that availability, remove it from consideration, and repeat the proportional
    split of whatever overflowed among the files still with headroom -- standard
    water-filling. Every step uses the same largest-remainder tie-break (by
    fractional part, ties broken by the fixed WEIGHTS order) as a flat split
    would, so the whole procedure is deterministic for a given (budget, weights,
    availability) and terminates in at most len(weights) rounds (each round either
    finishes, or removes at least one file from consideration for good)."""
    order = list(weights.keys())
    quotas = {f: 0 for f in order}
    active = set(order)
    to_place = min(budget, sum(availability.values()))

    while to_place > 0 and active:
        weight_total = sum(weights[f] for f in active)
        raw = {f: to_place * weights[f] / weight_total for f in active}
        floors = {f: int(raw[f]) for f in active}
        remainder = to_place - sum(floors.values())
        by_fraction = sorted(active, key=lambda f: (-(raw[f] - floors[f]), order.index(f)))
        for f in by_fraction[: max(remainder, 0)]:
            floors[f] += 1

        overflow = 0
        newly_capped = []
        for f in active:
            proposed = quotas[f] + floors[f]
            cap = availability[f]
            if proposed > cap:
                overflow += proposed - cap
                quotas[f] = cap
                newly_capped.append(f)
            else:
                quotas[f] = proposed
        for f in newly_capped:
            active.discard(f)
        to_place = overflow

    return quotas


def select_mutants(candidates_by_file: dict[str, list[MutationCandidate]], quotas: dict[str, int], seed: int):
    """Deterministic selection: exact pool if it fits the quota, else a fixed-seed
    random.Random(seed).sample() of the already-sorted pool, re-sorted afterward.
    A fresh Random(seed) is used per file so a given file's sample never depends on
    which other files were processed first."""
    selected: list[MutationCandidate] = []
    capped: list[str] = []
    for relpath, quota in quotas.items():
        pool = candidates_by_file.get(relpath, [])
        effective_quota = min(quota, len(pool))
        if effective_quota < quota:
            capped.append(relpath)
        if len(pool) <= effective_quota:
            chosen = list(pool)
        else:
            chosen = random.Random(seed).sample(pool, effective_quota)
            chosen.sort(key=lambda c: c.sort_key())
        selected.extend(chosen)
    selected.sort(key=lambda c: c.sort_key())
    return selected, capped


# ---------------------------------------------------------------------------
# Real-tree integrity: hash manifest of src/ and scripts/
# ---------------------------------------------------------------------------


def collect_guarded_files(repo_root: Path) -> list[Path]:
    files = []
    for base in ("src", "scripts"):
        for p in sorted((repo_root / base).rglob("*")):
            if p.is_file() and "__pycache__" not in p.parts:
                files.append(p)
    return files


def compute_manifest(paths: list[Path]) -> dict[str, str]:
    return {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}


def manifest_digest(manifest: dict[str, str]) -> str:
    combined = "\n".join(f"{k}:{v}" for k, v in sorted(manifest.items()))
    return hashlib.sha256(combined.encode()).hexdigest()


def verify_manifest_or_abort(before: dict[str, str], after: dict[str, str]) -> None:
    if before == after:
        return
    changed = sorted(set(before) ^ set(after)) or [k for k in before if before[k] != after.get(k)]
    raise SystemExit(
        "ABORT: real src/ or scripts/ changed during the mutation run. "
        f"Affected paths: {changed}. This must never happen; the mutation loop only "
        "ever writes inside the scratch tree. Investigate before trusting any other "
        "output of this run."
    )


# ---------------------------------------------------------------------------
# Scratch tree
# ---------------------------------------------------------------------------


def prepare_scratch_tree(repo_root: Path, scratch_root: Path) -> Path:
    if scratch_root.exists():
        shutil.rmtree(scratch_root)

    def ignore(_dir, names):
        return [n for n in names if n in EXCLUDE_DIR_NAMES]

    shutil.copytree(repo_root, scratch_root, ignore=ignore)
    return scratch_root


def run_pytest(cwd: Path, pytest_args: list[str], timeout_s: int) -> tuple[bool, str]:
    """Returns (all_passed, tail_of_output). A non-zero return code from pytest, or
    a timeout, both count as 'a test failed / detected something wrong' (a mutant
    that hangs a test has still been caught, just by a different symptom)."""
    cmd = [sys.executable, "-m", "pytest", "-p", "no:cacheprovider", *pytest_args]
    try:
        proc = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True, timeout=timeout_s)
        return proc.returncode == 0, (proc.stdout[-2000:] + proc.stderr[-500:])
    except subprocess.TimeoutExpired:
        return False, f"TIMEOUT after {timeout_s}s"


def targeted_pytest_args(relpath: str) -> list[str]:
    # No -n here, deliberately, for every file including capacity.py: xdist worker
    # startup (several seconds to spin up N workers) dominates a single targeted
    # module subset, and -x means a KILLED mutant (the common case) stops at the
    # first failing test anyway, so there is nothing to parallelize against for
    # most mutants. -n only pays for itself on the FULL suite confirmation step
    # (FULL_SUITE_ARGS below), which always runs to completion since it is only
    # invoked for mutants that already survived the fast targeted pass.
    return ["-q", "--no-header", "-x", *TARGETED_TESTS[relpath]]


